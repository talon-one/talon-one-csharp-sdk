        }

        /// <summary>
        /// Verifies that disabled rate limiting returns the configured token without waiting for timer ticks.
        /// </summary>
        [Fact]
        public async Task GetAsyncReturnsImmediatelyWhenRateLimitingIsDisabled()
        {
            ApiKeyToken token = new ApiKeyToken("<token>", ClientUtils.ApiKeyHeader.Authorization);
            ServiceCollection services = new ServiceCollection();

            new HostConfiguration(services).AddTokens(token, enableRateLimiting: false);

            TokenContainer<ApiKeyToken> container = services.BuildServiceProvider().GetRequiredService<TokenContainer<ApiKeyToken>>();
            TestableRateLimitProvider provider = new TestableRateLimitProvider(container);
            Assert.False(provider.IsRateLimitingEnabled);

            using (CancellationTokenSource cancellation = new CancellationTokenSource(TimeSpan.FromSeconds(5)))
            {
                Task<ApiKeyToken>[] requests = Enumerable.Range(0, 250)
                    .Select(_ => provider.GetTokenAsync("Authorization", cancellation.Token).AsTask())
                    .ToArray();

                ApiKeyToken[] results = await Task.WhenAll(requests).ConfigureAwait(false);

                Assert.All(results, result => Assert.Same(token, result));
            }
        }

        private sealed class TestableRateLimitProvider : RateLimitProvider<ApiKeyToken>
        {
            public TestableRateLimitProvider(TokenContainer<ApiKeyToken> container)
                : base(container)
            {
            }

            public ValueTask<ApiKeyToken> GetTokenAsync(string header, CancellationToken cancellation)
            {
                return GetAsync(header, cancellation);
            }
        }
